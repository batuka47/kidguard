"""Inventory of data/raw/: counts, sizes, label folders, example file names.

For each dataset folder in data/raw/ it reports files by extension, total size,
the label folders (folders that directly contain files; their names are the
original labels) and a few example file names per folder. It then checks the
folder names against scripts/label_map.yaml and lists every mismatch.

No image is opened or displayed: only os.walk and file sizes are used.
For datasets marked `sensitive: true` (or not in the label map at all), an
example file name is shown only if it is neutral (numbers / hashes / generic
words); otherwise it is replaced by <redacted> and counted (CLAUDE.md).

Skipped: _download/ caches, _COMPLETE.json / _meta.csv, dot files, *.part.

    python scripts/inventory.py
"""

import argparse
import fnmatch
import os
import re
from collections import Counter, defaultdict
from pathlib import Path

import yaml

NEUTRAL_WORDS = {"img", "image", "images", "frame", "photo", "pic", "dsc", "dscn", "screenshot",
                 "file", "train", "test", "val", "copy", "jpg", "jpeg", "png"}


def is_neutral(filename: str) -> bool:
    stem = Path(filename).stem.lower()
    stem = re.sub(r"[0-9a-f]{8,}", " ", stem)  # hashes / uuids
    words = [w for w in re.split(r"[^a-z]+", stem) if w]
    return all(w in NEUTRAL_WORDS or len(w) <= 2 for w in words)


def lookup(labels: dict, folder: str) -> tuple[str | None, str | None]:
    """(class, matching key) for a folder name; exact keys win over patterns."""
    if folder in labels:
        return labels[folder], folder
    for key, cls in labels.items():
        if any(ch in key for ch in "*?[") and fnmatch.fnmatchcase(folder, key):
            return cls, key
    return None, None


def scan(d: Path):
    leaf: dict[str, list[str]] = defaultdict(list)
    exts: Counter[str] = Counter()
    size = skipped = 0
    for dirpath, dirnames, filenames in os.walk(d):
        dirnames[:] = sorted(x for x in dirnames if not x.startswith(("_", ".")))
        for f in filenames:
            if f.startswith(("_", ".")) or f.endswith(".part"):
                skipped += 1
                continue
            rel = Path(dirpath).relative_to(d).as_posix()
            leaf[rel].append(f)
            exts[Path(f).suffix.lower() or "(none)"] += 1
            size += os.path.getsize(os.path.join(dirpath, f))
    return leaf, exts, size, skipped


def main() -> int:
    ap = argparse.ArgumentParser(description="Inventory of data/raw/ (file names and counts only).")
    ap.add_argument("--root", type=Path, default=Path("data/raw"))
    ap.add_argument("--label-map", type=Path, default=Path("scripts/label_map.yaml"))
    ap.add_argument("--out", type=Path, default=Path("reports/inventory.md"))
    ap.add_argument("--examples", type=int, default=3)
    args = ap.parse_args()

    cfg = (yaml.safe_load(args.label_map.read_text(encoding="utf-8")) or {}).get("datasets", {})
    datasets = sorted(p.name for p in args.root.iterdir() if p.is_dir() and not p.name.startswith(("_", ".")))
    md = ["# Raw data inventory", "",
          "Generated by `scripts/inventory.py`. File names and counts only; no image was opened.", "",
          "| dataset | complete | files | size GB | extensions | label folders | sensitive |",
          "|---|---|---|---|---|---|---|"]
    sections, mismatches = [], []
    totals = Counter()

    for name in datasets:
        d = args.root / name
        entry = cfg.get(name)
        labels = (entry or {}).get("labels") or {}
        sensitive = (entry or {}).get("sensitive", True)  # unknown dataset -> treat as sensitive
        leaf, exts, size, skipped = scan(d)
        files = sum(len(v) for v in leaf.values())
        complete = (d / "_COMPLETE.json").is_file()
        cache = sum(f.stat().st_size for f in (d / "_download").rglob("*") if f.is_file()) if (d / "_download").is_dir() else 0
        totals.update(files=files, size=size, cache=cache)
        ext_txt = ", ".join(f"{e} {n}" for e, n in exts.most_common())
        md.append(f"| {name} | {'yes' if complete else 'no'} | {files} | {size / 1e9:.2f} | {ext_txt} | "
                  f"{len(leaf)} | {'yes' if sensitive else 'no'} |")

        print(f"\n== {name}: {files} files, {size / 1e9:.2f} GB, complete={complete}, sensitive={sensitive}"
              f"{f', download cache {cache / 1e9:.2f} GB' if cache else ''}{f', {skipped} junk/meta files skipped' if skipped else ''}")
        print(f"   extensions: {ext_txt}")
        sec = [f"## {name}", "",
               f"{files} files, {size / 1e9:.2f} GB. Extensions: {ext_txt}."
               + (f" Download cache: {cache / 1e9:.2f} GB." if cache else ""), "",
               "| label folder (path) | maps to | files | examples |", "|---|---|---|---|"]
        redacted = 0
        used_keys = set()
        if entry is None:
            mismatches.append(f"{name}: dataset not in label_map.yaml")
        for rel, names in sorted(leaf.items()):
            folder = Path(rel).name if rel != "." else "(root)"
            cls, key = lookup(labels, folder)
            if key:
                used_keys.add(key)
            elif entry is not None:
                mismatches.append(f"{name}: folder '{rel}' ({len(names)} files) has no mapping")
            examples = []
            for f in sorted(names)[: args.examples]:
                if sensitive and not is_neutral(f):
                    examples.append("<redacted>")
                else:
                    examples.append(f)
            if sensitive:
                redacted += sum(not is_neutral(f) for f in names)
            print(f"   {len(names):7d}  {rel:55s} -> {cls or 'UNMAPPED':9s} e.g. {', '.join(examples)}")
            sec.append(f"| `{rel}` | {cls or '**unmapped**'} | {len(names)} | {', '.join(f'`{e}`' for e in examples)} |")
        for key in labels:
            if key not in used_keys and key != "*":
                mismatches.append(f"{name}: label_map key '{key}' matches no folder")
        if sensitive:
            note = f"Descriptive-looking file names (redacted above): {redacted} of {files}."
            print(f"   {note}")
            sec += ["", note]
        sections += sec + [""]

    for name in sorted(set(cfg) - set(datasets)):
        md_note = f"{name}: in label_map.yaml but not downloaded yet"
        print(f"\n== {md_note}")
        sections += [f"## {name}", "", "Not downloaded yet.", ""]

    md += ["", f"Total: {totals['files']} files, {totals['size'] / 1e9:.2f} GB "
               f"(+ {totals['cache'] / 1e9:.2f} GB of downloaded archives in `_download/`).", ""]
    md += sections + ["## Label map mismatches", ""] + ([f"- {m}" for m in mismatches] or ["None."]) + [""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(md), encoding="utf-8")

    print("\nLabel map mismatches:" + ("" if mismatches else " none"))
    for m in mismatches:
        print(f"  - {m}")
    print(f"Summary: {len(datasets)} datasets, {totals['files']} files, {totals['size'] / 1e9:.2f} GB "
          f"(+ {totals['cache'] / 1e9:.2f} GB archives), {len(mismatches)} mismatch(es); wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
